/**
 * جميع نصوص الحوارات والأصوات في مكان واحد
 * تدعم القوالب الديناميكية {name} و {character} لرفيق الطفل المختار
 */
export function formatDialogue(
  template: string,
  name: string = 'لؤلؤ',
  characterTitle: string = 'الأسد الصغير',
  gender: 'boy' | 'girl' = 'boy'
): string {
  if (!template) return '';
  const heroWord = gender === 'girl' ? 'بطلة' : 'بطل';
  const friendWord = gender === 'girl' ? 'صديقتي' : 'صديقي';
  const braveWord = gender === 'girl' ? 'شجاعة' : 'شجاع';
  const patientWord = gender === 'girl' ? 'صبورة' : 'صبور';

  return template
    .replace(/\{name\}/g, name)
    .replace(/\{character\}/g, characterTitle)
    .replace(/\{hero\}/g, heroWord)
    .replace(/\{friend\}/g, friendWord)
    .replace(/\{brave\}/g, braveWord)
    .replace(/\{patient\}/g, patientWord)
    .replace(/لؤلؤ/g, name);
}

